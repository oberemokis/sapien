import { describe, expect, it } from "vitest";
import { tagsOf } from "./tags";

describe("теги в тексте заметки", () => {
  it.each([
    ["#работа в начале строки", ["работа"]],
    ["созвон #работа и #q4-2024", ["работа", "q4-2024"]],
    ["- [ ] задача #срочно", ["срочно"]],
    ["вложенный #работа/sapien/", ["работа/sapien"]],
    ["## Заголовок #план", ["план"]],
  ])("%s", (text, tags) => {
    expect(tagsOf(text)).toEqual(tags);
  });

  it.each([
    ["заголовок", "# Заголовок\n## Подзаголовок"],
    ["одни цифры", "выпуск #2024"],
    ["блок кода", "```\n#include <stdio.h>\n```"],
    ["код с отступом", "    #define X"],
    ["код в строке", "команда `git log #123abc`"],
    ["адрес ссылки", "[документация](https://site.ru/page#раздел)"],
    ["адрес в угловых скобках", "<https://site.ru/#якорь>"],
    ["голый адрес", "https://site.ru/#якорь"],
    ["решётка внутри слова", "C# и a#b и &#38;"],
  ])("не тег: %s", (_case, text) => {
    expect(tagsOf(text)).toEqual([]);
  });

  it.each([
    ["строкой", "---\ntags: работа, план\n---\nтекст"],
    ["списком в скобках", "---\ntags: [работа, \"план\"]\n---\n"],
    ["строками ниже", "---\ntitle: x\ntags:\n  - работа\n  - '#план'\nauthor: я\n---\n"],
  ])("теги шапки %s", (_case, text) => {
    expect(tagsOf(text)).toEqual(["работа", "план"]);
  });

  it("шапка и текст вместе, регистр как написан", () => {
    expect(tagsOf("---\ntags: Работа\n---\n#работа")).toEqual(["Работа", "работа"]);
  });
});
